import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { chromium } from 'playwright';

await mkdir('tests/results', { recursive: true });
const url = process.env.APP_URL || 'http://127.0.0.1:5180/courtyard-restored.html';
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-webgl'] });
try {
  const page = await browser.newPage({ viewport: { width: 1538, height: 954 } });
  const errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) requests.push(r.url()); });
  assert.equal((await page.goto(url)).status(), 200);
  await page.waitForFunction(() => window.__ready);
  await page.evaluate(() => Promise.all([...document.images].map(i => i.decode())));
  assert.equal(await page.locator('#narration-speaker').innerText(), '旁白');
  assert.equal(await page.locator('#narration-text').innerText(), '晨光初透，长安渐醒。元和三年，白居易居于长安。新的一日，从庭院中的第一缕阳光开始。');
  const narrationStart = await page.locator('#narration').boundingBox();
  assert.equal(await page.locator('#garden .plant').count(), 5);
  assert.equal(await page.locator('#fence .plant').count(), 1);
  assert.equal(await page.locator('#column-picture').count(),1);
  assert(await page.locator('#column').evaluate(e=>+getComputedStyle(e).zIndex>+getComputedStyle(document.getElementById('architecture')).zIndex));
  assert(await page.locator('#fence').evaluate(e => +getComputedStyle(e).zIndex > +getComputedStyle(document.getElementById('garden')).zIndex));
  assert(await page.locator('#architecture').evaluate(e => +getComputedStyle(e).zIndex > +getComputedStyle(document.getElementById('fence')).zIndex));
  await page.screenshot({ path: 'tests/results/rest.png' });
  await page.mouse.wheel(0, 300);
  await page.waitForFunction(() => {
    const s = window.__sceneDebug;
    return s.zoom > 1.18 && s.walkEnergy > .1 && Math.abs(s.motion.flowers.lean) > .01 && Math.abs(s.motion.gap.lean) > .005;
  });
  await page.evaluate(() => { for (let i = 0; i < 8; i++) dispatchEvent(new WheelEvent('wheel', { deltaY: 300, cancelable: true })); });
  await page.waitForFunction(() => window.__sceneDebug.zoom > 2.3);
  await page.mouse.move(20, 477);
  await page.waitForFunction(() => window.__sceneDebug.x > 45);
  const left = await page.locator('#stage').boundingBox();
  await page.mouse.move(1518, 477);
  await page.waitForFunction(() => window.__sceneDebug.x < -45);
  const right = await page.locator('#stage').boundingBox();
  assert(left.x - right.x > 85);
  await page.mouse.move(769, 477);
  await page.waitForFunction(() => Math.abs(window.__sceneDebug.x) < .1 && window.__sceneDebug.walkEnergy < .01);
  await page.screenshot({ path: 'tests/results/zoom.png' });
  assert.deepEqual(await page.locator('#narration').boundingBox(), narrationStart);
  const before = (await page.evaluate(() => window.__sceneDebug)).targetZoom;
  await page.mouse.wheel(0, -300);
  await page.waitForFunction(v => window.__sceneDebug.targetZoom < v, before);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.waitForFunction(() => Object.values(window.__sceneDebug.motion).every(v => v.shift === 0 && v.lean === 0));
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  assert(await page.locator('#narration-text').evaluate(e => e.scrollHeight <= e.clientHeight));
  const narrationMobile = await page.locator('#narration').boundingBox();
  assert(narrationMobile.x >= 0 && narrationMobile.x + narrationMobile.width <= 390);
  await page.screenshot({ path: 'tests/results/mobile.png' });
  await page.keyboard.press('Home');
  await page.waitForFunction(() => window.__sceneDebug.zoom < 1.001);
  for (const viewport of [{width:1270,height:680},{width:1440,height:500},{width:640,height:360}]) {
    await page.setViewportSize(viewport);
    assert(await page.locator('#narration-text').evaluate(e => e.scrollHeight <= e.clientHeight + 1), `Dialogue text fits ${viewport.width}x${viewport.height}`);
    const box = await page.locator('#narration').boundingBox();
    assert(box.x >= 0 && box.y >= 0 && box.x + box.width <= viewport.width && box.y + box.height <= viewport.height);
    if (viewport.width === 1270) await page.screenshot({path:'tests/results/reference-layout.png'});
  }
  await page.setViewportSize({width:1270,height:680});
  const dialogueBox = await page.locator('#narration').boundingBox();
  await page.mouse.click(20,100);
  assert.equal(await page.locator('#narration-speaker').innerText(),'白居易');
  assert.equal(await page.locator('#narration-text').innerText(),'今日尚有公务，须早些出门。');
  assert.deepEqual(await page.locator('#narration').boundingBox(),dialogueBox);
  const alignment = await page.locator('#narration-text').evaluate(e=>{
    const range=document.createRange();range.selectNodeContents(e);
    const text=range.getBoundingClientRect(),box=e.getBoundingClientRect();
    return Math.abs(text.x+text.width/2-box.x-box.width/2);
  });
  assert(alignment<4,'Bai Juyi text is centered inside the light panel');
  await page.screenshot({path:'tests/results/bai-juyi.png'});
  await page.locator('#narration-text').click();
  assert.equal(await page.locator('#narration').isVisible(),false);
  await page.mouse.click(20,100);
  assert.equal(await page.locator('#narration').isVisible(),false);
  await page.screenshot({path:'tests/results/scene-only.png'});
  await page.mouse.wheel(0,300);
  await page.waitForFunction(()=>window.__sceneDebug.zoom>1.2);
  assert.equal(await page.locator('#narration').isVisible(),false);
  assert.deepEqual(errors, []);
  assert.deepEqual(requests, [url]);
  console.log('PASS: exact narration text; screen-fixed dialogue; mobile text fits; five plants; railing above flowers; wheel zoom; walking; bilateral parallax at 2.4x; reduced motion; no external requests/errors.');

  const noJS = await browser.newPage({ javaScriptEnabled: false });
  await noJS.goto(url);
  assert(await noJS.locator('#room').isVisible());
  await noJS.screenshot({ path: 'tests/results/no-js.png' });
  await noJS.close();
  const touch = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await touch.goto(url);
  await touch.waitForFunction(()=>window.__ready);
  assert.equal(await touch.locator('#narration-speaker').innerText(),'旁白');
  await touch.locator('#narration-text').tap();
  assert.equal(await touch.locator('#narration-speaker').innerText(),'白居易');
  assert.equal(await touch.locator('#narration-text').innerText(),'今日尚有公务，须早些出门。');
  assert(await touch.locator('#narration-text').evaluate(e=>e.scrollHeight<=e.clientHeight));
  await touch.screenshot({path:'tests/results/bai-juyi-mobile.png'});
  await touch.locator('#narration-text').tap();
  assert.equal(await touch.locator('#narration').isVisible(),false);
  await touch.touchscreen.tap(100,100);
  assert.equal(await touch.locator('#narration').isVisible(),false);
  await touch.close();
  const sandboxPage = await browser.newPage();
  const html = await readFile('/workspace/courtyard-restored.html', 'utf8');
  await sandboxPage.setContent('<iframe sandbox="allow-scripts" style="width:100vw;height:100vh;border:0"></iframe>');
  await sandboxPage.locator('iframe').evaluate((e, data) => e.srcdoc = data, html);
  const frame = await (await sandboxPage.locator('iframe').elementHandle()).contentFrame();
  await frame.waitForFunction(() => window.__ready);
  assert.equal(await frame.locator('#fence img').evaluate(i => i.complete && i.naturalWidth > 500), true);
  await frame.locator('body').click({position:{x:20,y:100}});
  assert.equal(await frame.locator('#narration-speaker').innerText(),'白居易');
  await frame.locator('#narration-text').click();
  assert.equal(await frame.locator('#narration').isVisible(),false);
  console.log('PASS: no-JavaScript scene and opaque-origin sandbox/srcdoc preview; no WebGL required.');
} finally { await browser.close(); }
